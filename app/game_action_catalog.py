# Exact names shared with moderation commands. Moderators get moderation by default;
# prefix `игра` or `game` forces the game action.
MODERATION_COLLISIONS = {"расен_сюрикен", "призыв_жаба"} | EXTRA_GAME_COLLISIONS | EXTRA_GAME_COLLISIONS
_MODERATION_COLLISION_KEYS = {
    re.sub(r"[\s_-]+", "_", _without_accents(value).casefold()).strip("_")
    for value in MODERATION_COLLISIONS
}


def is_moderation_collision(trigger: str) -> bool:
    key = re.sub(r"[\s_-]+", "_", _without_accents(trigger or "").casefold()).strip("_")
    return key in _MODERATION_COLLISION_KEYS


def default_game_actions() -> dict[int, dict[str, Any]]:
    return deepcopy(GAME_ACTIONS)


def command_aliases(command: dict[str, Any]) -> list[str]:
    values = [str(command.get("trigger") or ""), *(str(item) for item in command.get("aliases") or [])]
    return [value for value in dict.fromkeys(values) if value.strip()]


def strip_game_prefix(text: str) -> tuple[str, bool]:
    value = (text or "").strip()
    normalized = _without_accents(value).casefold()
    prefix_patterns = (
        r"^\s*/?игра(?:[\s_-]+)",
        r"^\s*/?game(?:[\s_-]+)",
    )
    for pattern in prefix_patterns:
        match = re.match(pattern, normalized, re.IGNORECASE)
        if match:
            return value[match.end():].lstrip(), True
    return value, False


def match_game_action(text: str, actions: dict[int, dict[str, Any]] | None = None) -> tuple[int, dict[str, Any], str, bool] | None:
    candidate, forced = strip_game_prefix(text)
    cleaned = _without_accents(candidate)
    catalog = actions or GAME_ACTIONS
    variants: list[tuple[int, int, dict[str, Any], re.Pattern[str]]] = []
    for key, command in catalog.items():
        for alias in command_aliases(command):
            variants.append((len(_without_accents(alias)), key, command, _pattern(alias)))
    for _, key, command, pattern in sorted(variants, key=lambda item: item[0], reverse=True):
        match = pattern.match(cleaned)
        if match:
            return key, command, cleaned[match.end():].strip(), forced
    return None
